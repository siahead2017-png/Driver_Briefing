/* Общее для экрана (app.js) и бумаги (print.js).
   Раньше esc() и plural() лежали в обоих файлах дословной копией —
   правка в одном месте не доезжала до другого. */

// Весь текст приходит из JSON и вставляется через innerHTML — экранируем.
export const esc = s => String(s ?? '').replace(/[&<>"']/g, c => (
  { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]
));

// «1 пункт», «2 пункта», «5 пунктов»
export function plural(n, one, few, many) {
  const m10 = n % 10, m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few;
  return many;
}

/* Место, которое ведущий подставляет голосом: {имя} в JSON.
   Сначала экранируем, потом ищем фигурные скобки — внутрь <span>
   попадает только уже безопасный текст, инъекция невозможна. */
export const slots = s => esc(s).replace(
  /\{([^{}]{1,40})\}/g, '<span class="slot">$1</span>'
);
